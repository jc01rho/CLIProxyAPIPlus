func openCodeStaticModel(id, displayName string, contextLength int) *ModelInfo {
	if contextLength <= 0 {
		contextLength = 200000
	}
	return &ModelInfo{
		ID:            id,
		Object:        "model",
		OwnedBy:       "opencode",
		Type:          "opencode",
		DisplayName:   displayName,
		ContextLength: contextLength,
		Created:       1789948940,
		Thinking:      &ThinkingSupport{Levels: []string{"low", "high", "max"}},
	}
}
